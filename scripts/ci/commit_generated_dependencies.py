def _mapping(value: object, description: str) -> Mapping[str, Any]:
    if not isinstance(value, Mapping):
        raise PublishError(f"missing or malformed {description}")
    return value


def _integer(value: object, description: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
        raise PublishError(f"{description} must be a positive integer")
    return value


def _string(value: object, description: str) -> str:
    if not isinstance(value, str) or not value:
        raise PublishError(f"{description} must be a non-empty string")
    return value


def _validate_repository(repository: str) -> None:
    if not REPOSITORY_PATTERN.fullmatch(repository):
        raise PublishError(f"invalid repository: {repository!r}")


def _validate_branch(branch: str) -> None:
    invalid_character = any(character.isspace() or ord(character) < 32 for character in branch)
    if (
        not branch
        or branch.startswith(("refs/", "/"))
        or branch.endswith(("/", "."))
        or ".." in branch
        or "@{" in branch
        or "//" in branch
        or invalid_character
        or any(character in branch for character in r"~^:?*[\ ")
    ):
        raise PublishError(f"invalid unqualified branch name: {branch!r}")


def _validate_oid(oid: str, description: str = "object ID") -> None:
    if not OID_PATTERN.fullmatch(oid):
        raise PublishError(f"{description} must be a lowercase 40- or 64-character hexadecimal object ID")


def _read_regular_file(path: Path, *, maximum_bytes: int, description: str) -> bytes:
    try:
        file_stat = path.lstat()
    except OSError as error:
        raise PublishError(f"unable to stat {description}: {error}") from error
    if stat.S_ISLNK(file_stat.st_mode) or not stat.S_ISREG(file_stat.st_mode):
        raise PublishError(f"{description} must be a regular non-symlink file")
    if file_stat.st_size > maximum_bytes:
        raise PublishError(f"{description} exceeds the {maximum_bytes}-byte limit")
    try:
        return path.read_bytes()
    except OSError as error:
        raise PublishError(f"unable to read {description}: {error}") from error


def _read_generated_files(repo_root: Path) -> dict[str, bytes]:
    return {
        relative_path: _read_regular_file(
            repo_root / relative_path,
            maximum_bytes=MAX_GENERATED_FILE_BYTES,
            description=f"generated file {relative_path}",
        )
        for relative_path in GENERATED_PATHS
    }


def _snapshot_document(contents: Mapping[str, bytes]) -> dict[str, object]:
    return {
        "schema_version": SNAPSHOT_SCHEMA,
        "files": [
            {
                "path": relative_path,
                "sha256": hashlib.sha256(contents[relative_path]).hexdigest(),
                "size": len(contents[relative_path]),
            }
            for relative_path in GENERATED_PATHS
        ],
    }


def write_dependency_snapshot(repo_root: Path, snapshot_path: Path) -> None:
    """Hash the final verified generated files into one exact snapshot."""
    if snapshot_path.exists() or snapshot_path.is_symlink():
        raise PublishError(f"dependency snapshot already exists: {snapshot_path}")
    contents = _read_generated_files(repo_root)
    snapshot_text = json.dumps(_snapshot_document(contents), indent=2, sort_keys=True) + "\n"
    if len(snapshot_text.encode()) > MAX_MANIFEST_BYTES:
        raise PublishError("dependency snapshot exceeds the trusted size limit")
    try:
        snapshot_path.parent.mkdir(parents=True, exist_ok=True)
        snapshot_path.write_text(snapshot_text, encoding="utf-8")
    except OSError as error:
        raise PublishError(f"unable to write dependency snapshot: {error}") from error


def _load_dependency_snapshot(snapshot_path: Path) -> dict[str, tuple[str, int]]:
    raw_snapshot = _read_regular_file(
        snapshot_path,
        maximum_bytes=MAX_MANIFEST_BYTES,
        description="verified dependency snapshot",
    )
    try:
        snapshot = json.loads(raw_snapshot)
    except (UnicodeDecodeError, json.JSONDecodeError) as error:
        raise PublishError("verified dependency snapshot is not valid JSON") from error
    snapshot_map = _mapping(snapshot, "verified dependency snapshot")
    if set(snapshot_map) != {"schema_version", "files"} or snapshot_map.get("schema_version") != SNAPSHOT_SCHEMA:
        raise PublishError("verified dependency snapshot has an invalid schema")
    raw_files = snapshot_map.get("files")
    if not isinstance(raw_files, list) or len(raw_files) != len(GENERATED_PATHS):
        raise PublishError("verified dependency snapshot must describe exactly three files")
    described: dict[str, tuple[str, int]] = {}
    for raw_entry in raw_files:
        entry = _mapping(raw_entry, "verified dependency snapshot file")
        if set(entry) != {"path", "sha256", "size"}:
            raise PublishError("verified dependency snapshot file has unexpected fields")
        relative_path = _string(entry.get("path"), "verified dependency snapshot path")
        digest = entry.get("sha256")
        size = entry.get("size")
        if relative_path not in GENERATED_PATHS or relative_path in described:
            raise PublishError("verified dependency snapshot has a duplicate or unexpected path")
        if not isinstance(digest, str) or not SHA256_PATTERN.fullmatch(digest):
            raise PublishError("verified dependency snapshot has an invalid digest")
        if isinstance(size, bool) or not isinstance(size, int) or size < 0:
            raise PublishError("verified dependency snapshot has an invalid size")
        described[relative_path] = (digest, size)
    if set(described) != set(GENERATED_PATHS):
        raise PublishError("verified dependency snapshot does not describe the exact generated file set")
    return described


def package_artifact(
    *,
    repo_root: Path,
    artifact_root: Path,
    repository: str,
    pr_number: int,
    head_repository: str,
    head_ref: str,
    head_sha: str,
    run_id: int,
    run_attempt: int,
    producer_status: str,
    changed: bool,
    snapshot_path: Path,
) -> None:
    """Create the exact four-file producer artifact."""
    _validate_repository(repository)
    if head_repository != repository:
        raise PublishError("Dependabot head repository must equal the target repository")
    _validate_branch(head_ref)
    _validate_oid(head_sha, "source head")
    _integer(pr_number, "pull request number")
    _integer(run_id, "workflow run ID")
    _integer(run_attempt, "workflow run attempt")
    if producer_status not in {"success", "failure", "cancelled"}:
        raise PublishError(f"invalid producer status: {producer_status!r}")
    if artifact_root.exists():
        raise PublishError(f"artifact root already exists: {artifact_root}")

    contents = _read_generated_files(repo_root)
    snapshot = _load_dependency_snapshot(snapshot_path)
    for relative_path in GENERATED_PATHS:
        digest, size = snapshot[relative_path]
        content = contents[relative_path]
        if hashlib.sha256(content).hexdigest() != digest or len(content) != size:
            raise PublishError(f"generated file changed after verified snapshot: {relative_path}")

    file_entries: list[dict[str, object]] = []
    for relative_path in GENERATED_PATHS:
        content = contents[relative_path]
        file_entries.append(
            {
                "path": relative_path,
                "sha256": hashlib.sha256(content).hexdigest(),
                "size": len(content),
            }
        )

    manifest = {
        "schema_version": ARTIFACT_SCHEMA,
        "producer": ARTIFACT_PRODUCER,
        "repository": repository,
        "pr_number": pr_number,
        "head_repository": head_repository,
        "head_ref": head_ref,
        "head_sha": head_sha,
        "workflow_run_id": run_id,
        "workflow_run_attempt": run_attempt,
        "producer_status": producer_status,
        "changed": changed,
        "files": file_entries,
    }
    manifest_text = json.dumps(manifest, indent=2, sort_keys=True) + "\n"
    if _read_generated_files(repo_root) != contents:
        raise PublishError("generated files changed while packaging the verified snapshot")
    artifact_root.mkdir(parents=True)
    for relative_path in GENERATED_PATHS:
        (artifact_root / relative_path).write_bytes(contents[relative_path])
    (artifact_root / MANIFEST_NAME).write_text(manifest_text, encoding="utf-8")
    if _read_generated_files(repo_root) != contents:
        raise PublishError("generated files changed while packaging the verified snapshot")


def load_run_context(event_path: Path, *, target_repository: str) -> RunContext:
    """Validate the workflow_run event independently of artifact claims."""
    _validate_repository(target_repository)
    event_bytes = _read_regular_file(
        event_path,
        maximum_bytes=MAX_MANIFEST_BYTES * 8,
        description="workflow event",
    )
    try:
        event = json.loads(event_bytes)
    except (UnicodeDecodeError, json.JSONDecodeError) as error:
        raise PublishError("workflow event is not valid JSON") from error
    event_map = _mapping(event, "workflow event")
    repository = _mapping(event_map.get("repository"), "workflow event repository")
    if repository.get("full_name") != target_repository:
        raise PublishError("workflow event repository does not match TARGET_REPOSITORY")
    default_branch = _string(repository.get("default_branch"), "default branch")
    _validate_branch(default_branch)

    workflow_run = _mapping(event_map.get("workflow_run"), "workflow_run")
    if workflow_run.get("name") != GENERATOR_WORKFLOW:
        raise PublishError("workflow_run came from an unexpected workflow")
    if workflow_run.get("path") != GENERATOR_WORKFLOW_PATH:
        raise PublishError("workflow_run came from an unexpected workflow path")
    if workflow_run.get("event") != "pull_request" or workflow_run.get("conclusion") != "success":
        raise PublishError("workflow_run must be a successful pull_request run")
    actor = _mapping(workflow_run.get("actor"), "workflow_run actor")
    if actor.get("login") != BOT_LOGIN:
        raise PublishError("workflow_run actor is not Dependabot")
    head_repository = _mapping(workflow_run.get("head_repository"), "workflow_run head repository")
    if head_repository.get("full_name") != target_repository:
        raise PublishError("workflow_run head repository is not the target repository")
    run_repository = _mapping(workflow_run.get("repository"), "workflow_run repository")
    if run_repository.get("full_name") != target_repository:
        raise PublishError("workflow_run repository is not the target repository")

    head_ref = _string(workflow_run.get("head_branch"), "workflow_run head branch")
    head_sha = _string(workflow_run.get("head_sha"), "workflow_run head SHA")
    _validate_branch(head_ref)
    _validate_oid(head_sha, "workflow_run head SHA")
    return RunContext(
        repository=target_repository,
        default_branch=default_branch,
        head_ref=head_ref,
        head_sha=head_sha,
        run_id=_integer(workflow_run.get("id"), "workflow run ID"),
        run_attempt=_integer(workflow_run.get("run_attempt"), "workflow run attempt"),
        workflow_id=_integer(workflow_run.get("workflow_id"), "workflow ID"),
        repository_id=_integer(repository.get("id"), "repository ID"),
        head_repository_id=_integer(head_repository.get("id"), "head repository ID"),
    )


def validate_artifact_listing(
    response: Mapping[str, Any],
    *,
    context: RunContext,
) -> ArtifactMetadata:
    """Authenticate one bounded, non-expired artifact before downloading it."""
    total_count = response.get("total_count")
    raw_artifacts = response.get("artifacts")
    if total_count != 1 or not isinstance(raw_artifacts, list) or len(raw_artifacts) != 1:
        raise PublishError("source workflow run must publish exactly one dependency artifact")
    artifact = _mapping(raw_artifacts[0], "dependency artifact metadata")
    if artifact.get("name") != ARTIFACT_NAME:
        raise PublishError("dependency artifact has an unexpected name")
    if artifact.get("expired") is not False:
        raise PublishError("dependency artifact is expired or has no expiry state")
    artifact_id = _integer(artifact.get("id"), "dependency artifact ID")
    size_in_bytes = _integer(artifact.get("size_in_bytes"), "dependency artifact archive size")
    if size_in_bytes > MAX_ARTIFACT_ARCHIVE_BYTES:
        raise PublishError("dependency artifact archive size exceeds the trusted limit")
    raw_digest = artifact.get("digest")
    if not isinstance(raw_digest, str) or not raw_digest.startswith("sha256:"):
        raise PublishError("dependency artifact digest is missing or malformed")
    digest = raw_digest.removeprefix("sha256:")
    if not SHA256_PATTERN.fullmatch(digest):
        raise PublishError("dependency artifact digest is missing or malformed")

    source = _mapping(artifact.get("workflow_run"), "dependency artifact source workflow run")
    expected_source = {
        "id": context.run_id,
        "repository_id": context.repository_id,
        "head_repository_id": context.head_repository_id,
        "head_branch": context.head_ref,
        "head_sha": context.head_sha,
    }
    for field, expected in expected_source.items():
        if source.get(field) != expected:
            raise PublishError(f"dependency artifact source workflow run {field} does not match")
    return ArtifactMetadata(
        artifact_id=artifact_id,
        size_in_bytes=size_in_bytes,
        digest=digest,
    )


def read_safe_artifact_archive(archive: bytes) -> dict[str, bytes]:
    """Read the exact flat artifact in memory with no filesystem extraction."""
    if not archive or len(archive) > MAX_ARTIFACT_ARCHIVE_BYTES:
        raise PublishError("dependency artifact archive size exceeds the trusted limit")
    try:
        with zipfile.ZipFile(io.BytesIO(archive), mode="r") as bundle:
            entries = bundle.infolist()
            names = [entry.filename for entry in entries]
            if len(set(names)) != len(names):
                raise PublishError("dependency artifact archive contains a duplicate path")
            expected_names = {*GENERATED_PATHS, MANIFEST_NAME}
            if len(entries) != len(expected_names) or set(names) != expected_names:
                raise PublishError("dependency artifact archive must contain the exact flat file set")

            total_uncompressed = 0
            contents: dict[str, bytes] = {}
            for entry in entries:
                if entry.is_dir() or "/" in entry.filename or "\\" in entry.filename or entry.filename in {".", ".."}:
                    raise PublishError("dependency artifact archive must contain exact flat regular files")
                mode = entry.external_attr >> 16
                if mode and stat.S_ISLNK(mode):
                    raise PublishError("dependency artifact archive must not contain symlink entries")
                if entry.flag_bits & 0x1:
                    raise PublishError("dependency artifact archive must not contain encrypted entries")
                if entry.compress_type not in {zipfile.ZIP_STORED, zipfile.ZIP_DEFLATED}:
                    raise PublishError("dependency artifact archive uses an unsupported compression method")
                maximum_bytes = MAX_MANIFEST_BYTES if entry.filename == MANIFEST_NAME else MAX_GENERATED_FILE_BYTES
                if entry.file_size > maximum_bytes:
                    raise PublishError(f"dependency artifact entry exceeds its size limit: {entry.filename}")
                total_uncompressed += entry.file_size
                if total_uncompressed > (MAX_MANIFEST_BYTES + len(GENERATED_PATHS) * MAX_GENERATED_FILE_BYTES):
                    raise PublishError("dependency artifact uncompressed size exceeds the trusted limit")
                with bundle.open(entry, mode="r") as source:
                    content = source.read(maximum_bytes + 1)
                    if len(content) > maximum_bytes or source.read(1):
                        raise PublishError(f"dependency artifact entry exceeds its size limit: {entry.filename}")
                if len(content) != entry.file_size:
                    raise PublishError(f"dependency artifact entry size is contradictory: {entry.filename}")
                contents[entry.filename] = content
    except (OSError, RuntimeError, zipfile.BadZipFile) as error:
        raise PublishError(f"dependency artifact is not a safe ZIP archive: {error}") from error
    return contents


def _artifact_redirect_url(
    metadata: ArtifactMetadata,
    context: RunContext,
    *,
    token: str,
    opener: UrlOpener | None = None,
) -> str:
    """Resolve GitHub's authenticated redirect without forwarding credentials."""
    if not token:
        raise PublishError("GITHUB_TOKEN is missing")
    request = urllib.request.Request(
        f"{_api_root(context.repository)}/actions/artifacts/{metadata.artifact_id}/zip",
        headers={
            "Accept": "application/vnd.github+json",
            "Authorization": f"Bearer {token}",
            "User-Agent": "Odyssey-dependency-publisher",
            "X-GitHub-Api-Version": "2022-11-28",
        },
        method="GET",
    )
    redirect_opener = opener
    if redirect_opener is None:
        redirect_opener = urllib.request.build_opener(_NoRedirectHandler()).open
    location: str | None = None
    try:
        with redirect_opener(request, timeout=30) as response:
            status_code = int(response.status)
            if status_code not in {302, 303, 307, 308}:
                raise PublishError(f"artifact download redirect returned HTTP {status_code}")
            location = response.headers.get("Location")
    except urllib.error.HTTPError as error:
        if error.code not in {302, 303, 307, 308}:
            raise PublishError(f"artifact download redirect failed with HTTP {error.code}") from error
        location = error.headers.get("Location")
        error.close()
    except (urllib.error.URLError, TimeoutError, OSError) as error:
        raise PublishError(f"artifact download redirect failed: {error}") from error
    if not location:
        raise PublishError("artifact download redirect omitted its signed location")
    parsed = urllib.parse.urlsplit(location)
    if parsed.scheme != "https" or not parsed.hostname or parsed.username is not None or parsed.password is not None:
        raise PublishError("artifact download redirect returned an unsafe location")
    return location


def download_artifact_archive(
    metadata: ArtifactMetadata,
    context: RunContext,
    *,
    token: str,
    redirect_opener: UrlOpener | None = None,
    download_opener: UrlOpener = urllib.request.urlopen,
) -> bytes:
    """Download one bounded archive by immutable artifact ID without auth forwarding."""
    signed_url = _artifact_redirect_url(
        metadata,
        context,
        token=token,
        opener=redirect_opener,
    )
    request = urllib.request.Request(
        signed_url,
        headers={"Accept": "application/zip", "User-Agent": "Odyssey-dependency-publisher"},
        method="GET",
    )
    try:
        with download_opener(request, timeout=30) as response:
            status_code = int(response.status)
            if status_code != 200:
                raise PublishError(f"artifact archive download failed with HTTP {status_code}")
            content_length = response.headers.get("Content-Length")
            if content_length is not None:
                try:
                    declared_length = int(content_length)
                except ValueError as error:
                    raise PublishError("artifact archive download returned an invalid length") from error
                if declared_length <= 0:
                    raise PublishError("artifact archive download returned an invalid length")
                if declared_length > MAX_ARTIFACT_ARCHIVE_BYTES:
                    raise PublishError("artifact archive download exceeds the trusted size limit")
            archive = response.read(MAX_ARTIFACT_ARCHIVE_BYTES + 1)
    except urllib.error.HTTPError as error:
        raise PublishError(f"artifact archive download failed with HTTP {error.code}") from error
    except (urllib.error.URLError, TimeoutError, OSError) as error:
        raise PublishError(f"artifact archive download failed: {error}") from error
    if not archive or len(archive) > MAX_ARTIFACT_ARCHIVE_BYTES:
        raise PublishError("artifact archive download exceeds the trusted size limit")
    return archive


def download_validated_artifact(
    context: RunContext,
    *,
    token: str,
    opener: UrlOpener = urllib.request.urlopen,
) -> ArtifactBundle:
    """Preflight, download, and validate one untrusted artifact entirely in memory."""
    query = urllib.parse.urlencode({"name": ARTIFACT_NAME, "per_page": 100})
    listing = _rest_get(
        f"{_api_root(context.repository)}/actions/runs/{context.run_id}/artifacts?{query}",
        token=token,
        opener=opener,
        description="dependency artifact listing",
    )
    if listing is None:
        raise PublishError("dependency artifact listing unexpectedly returned no response")
    metadata = validate_artifact_listing(listing, context=context)
    archive = download_artifact_archive(metadata, context, token=token)
    if len(archive) != metadata.size_in_bytes:
        raise PublishError("dependency artifact archive size contradicts GitHub metadata")
    if hashlib.sha256(archive).hexdigest() != metadata.digest:
        raise PublishError("dependency artifact archive digest contradicts GitHub metadata")
    entries = read_safe_artifact_archive(archive)
    return validate_artifact_entries(entries, context=context)


def validate_artifact(artifact_root: Path, *, context: RunContext) -> ArtifactBundle:
    """Fail closed unless the artifact is exact, internally valid, and event-bound."""
    if artifact_root.is_symlink() or not artifact_root.is_dir():
        raise PublishError("artifact root must be a regular directory")
    expected_names = {*GENERATED_PATHS, MANIFEST_NAME}
    try:
        entries = list(artifact_root.iterdir())
    except OSError as error:
        raise PublishError(f"unable to list artifact root: {error}") from error
    actual_names = {entry.name for entry in entries}
    if len(entries) != len(expected_names) or actual_names != expected_names:
        raise PublishError(f"artifact must contain exactly {sorted(expected_names)}; found {sorted(actual_names)}")
    if any(entry.is_symlink() or not entry.is_file() for entry in entries):
        raise PublishError("artifact entries must all be regular non-symlink files")

    contents = {
        entry.name: _read_regular_file(
            entry,
            maximum_bytes=MAX_MANIFEST_BYTES if entry.name == MANIFEST_NAME else MAX_GENERATED_FILE_BYTES,
            description=f"artifact entry {entry.name}",
        )
        for entry in entries
    }
    return validate_artifact_entries(contents, context=context)


def validate_artifact_entries(
    contents: Mapping[str, bytes],
    *,
    context: RunContext,
) -> ArtifactBundle:
    """Validate exact in-memory artifact entries against the workflow event."""
    expected_names = {*GENERATED_PATHS, MANIFEST_NAME}
    if set(contents) != expected_names or len(contents) != len(expected_names):
        raise PublishError(f"artifact must contain exactly {sorted(expected_names)}")
    for name, content in contents.items():
        maximum_bytes = MAX_MANIFEST_BYTES if name == MANIFEST_NAME else MAX_GENERATED_FILE_BYTES
        if not isinstance(content, bytes) or len(content) > maximum_bytes:
            raise PublishError(f"artifact entry is malformed or exceeds its size limit: {name}")

    manifest_bytes = contents[MANIFEST_NAME]
    try:
        manifest = json.loads(manifest_bytes)
    except (UnicodeDecodeError, json.JSONDecodeError) as error:
        raise PublishError("artifact manifest is not valid JSON") from error
    manifest_map = _mapping(manifest, "artifact manifest")
    expected_keys = {
        "schema_version",
        "producer",
        "repository",
        "pr_number",
        "head_repository",
        "head_ref",
        "head_sha",
        "workflow_run_id",
        "workflow_run_attempt",
        "producer_status",
        "changed",
        "files",
    }
    if set(manifest_map) != expected_keys:
        raise PublishError("artifact manifest has missing or unexpected fields")
    expected_metadata = {
        "schema_version": ARTIFACT_SCHEMA,
        "producer": ARTIFACT_PRODUCER,
        "repository": context.repository,
        "head_repository": context.repository,
        "head_ref": context.head_ref,
        "head_sha": context.head_sha,
        "workflow_run_id": context.run_id,
        "workflow_run_attempt": context.run_attempt,
        "producer_status": "success",
    }
    for key, expected_value in expected_metadata.items():
        if manifest_map.get(key) != expected_value:
            raise PublishError(f"artifact manifest {key} does not match the workflow event")
    pr_number = _integer(manifest_map.get("pr_number"), "artifact pull request number")
    changed = manifest_map.get("changed")
    if not isinstance(changed, bool):
        raise PublishError("artifact manifest changed field must be boolean")

    raw_file_entries = manifest_map.get("files")
    if not isinstance(raw_file_entries, list) or len(raw_file_entries) != len(GENERATED_PATHS):
        raise PublishError("artifact manifest must describe exactly three generated files")
    described_paths: set[str] = set()
    files: dict[str, bytes] = {}
    for raw_entry in raw_file_entries:
        entry = _mapping(raw_entry, "artifact file entry")
        if set(entry) != {"path", "sha256", "size"}:
            raise PublishError("artifact file entry has missing or unexpected fields")
        relative_path = _string(entry.get("path"), "artifact file path")
        if relative_path not in GENERATED_PATHS or relative_path in described_paths:
            raise PublishError(f"artifact manifest has duplicate or unexpected path: {relative_path}")
        described_paths.add(relative_path)
        content = contents[relative_path]
        digest = entry.get("sha256")
        size = entry.get("size")
        if not isinstance(digest, str) or not SHA256_PATTERN.fullmatch(digest):
            raise PublishError(f"artifact manifest has invalid SHA-256 for {relative_path}")
        if isinstance(size, bool) or not isinstance(size, int) or size < 0:
            raise PublishError(f"artifact manifest has invalid size for {relative_path}")
        if hashlib.sha256(content).hexdigest() != digest or len(content) != size:
            raise PublishError(f"artifact file contradicts its manifest: {relative_path}")
        files[relative_path] = content
    if described_paths != set(GENERATED_PATHS):
        raise PublishError("artifact manifest does not describe the exact generated file set")

    return ArtifactBundle(
        repository=context.repository,
        pr_number=pr_number,
        head_ref=context.head_ref,
        head_sha=context.head_sha,
        changed=changed,
        files=files,
    )


def _parse_toml_document(content: bytes, description: str) -> dict[str, Any]:
    try:
        document = tomllib.loads(content.decode("utf-8"))
    except (UnicodeDecodeError, tomllib.TOMLDecodeError) as error:
        raise PublishError(f"{description} is not valid UTF-8 TOML") from error
    if not isinstance(document, dict):
        raise PublishError(f"{description} is not a TOML document")
    return document


def _dependency_parts(requirement: object, description: str) -> tuple[str, str, str]:
    if not isinstance(requirement, str) or not requirement:
        raise PublishError(f"{description} must contain only dependency strings")
    if (
        requirement != requirement.strip()
        or "\n" in requirement
        or "\r" in requirement
        or "@" in requirement
        or "/" in requirement
        or "\\" in requirement
        or "://" in requirement
        or requirement.startswith("-")
    ):
        raise PublishError(f"{description} contains an unsafe dependency URL, path, or option")
    match = DEPENDENCY_NAME_PATTERN.match(requirement)
    if match is None:
        raise PublishError(f"{description} contains a malformed dependency")
    specifier = requirement[match.end() :]
    if not DEPENDENCY_SPECIFIER_PATTERN.fullmatch(specifier):
        raise PublishError(f"{description} contains an unsupported dependency specifier")
    raw_name = match.group(0)
    normalized_name = re.sub(r"[-_.]+", "-", raw_name).lower()
    normalized_specifier = re.sub(r"\s+", "", specifier)
    return raw_name, normalized_name, normalized_specifier


def _dependency_name(requirement: object, description: str) -> str:
    return _dependency_parts(requirement, description)[1]


def _dependency_lists(document: Mapping[str, Any], description: str) -> dict[tuple[str, ...], list[str]]:
    locations: dict[tuple[str, ...], list[str]] = {}
    build_system = _mapping(document.get("build-system"), f"{description} build-system")
    project = _mapping(document.get("project"), f"{description} project")
    dependency_groups = _mapping(document.get("dependency-groups"), f"{description} dependency-groups")
    raw_locations: dict[tuple[str, ...], object] = {
        ("build-system", "requires"): build_system.get("requires"),
        ("project", "dependencies"): project.get("dependencies"),
        **{
            ("dependency-groups", str(group)): dependencies
            for group, dependencies in dependency_groups.items()
            if isinstance(group, str)
        },
    }
    if len(raw_locations) != len(dependency_groups) + 2:
        raise PublishError(f"{description} dependency groups have malformed names")
    for location, raw_dependencies in raw_locations.items():
        if not isinstance(raw_dependencies, list):
            raise PublishError(f"{description} {'.'.join(location)} must be a dependency list")
        dependencies = list(raw_dependencies)
        for dependency in dependencies:
            _dependency_name(dependency, f"{description} {'.'.join(location)}")
        locations[location] = dependencies
    return locations


def _replace_nested(document: dict[str, Any], location: tuple[str, ...], value: object) -> None:
    target = document
    for key in location[:-1]:
        nested = target.get(key)
        if not isinstance(nested, dict):
            raise PublishError("project metadata changed outside dependency declarations")
        target = nested
    target[location[-1]] = value


def _validate_candidate_pyproject(candidate: bytes, trusted: bytes) -> None:
    candidate_document = _parse_toml_document(candidate, "candidate pyproject.toml")
    trusted_document = _parse_toml_document(trusted, "trusted pyproject.toml")
    candidate_dependencies = _dependency_lists(candidate_document, "candidate pyproject.toml")
    trusted_dependencies = _dependency_lists(trusted_document, "trusted pyproject.toml")
    if set(candidate_dependencies) != set(trusted_dependencies):
        raise PublishError("candidate pyproject.toml changed dependency group structure")

    normalized_candidate = copy.deepcopy(candidate_document)
    for location, trusted_values in trusted_dependencies.items():
        candidate_values = candidate_dependencies[location]
        candidate_names = [
            _dependency_name(value, f"candidate pyproject.toml {'.'.join(location)}") for value in candidate_values
        ]
        trusted_names = [
            _dependency_name(value, f"trusted pyproject.toml {'.'.join(location)}") for value in trusted_values
        ]
        if candidate_names != trusted_names:
            raise PublishError(
                f"candidate pyproject.toml may change versions but not dependency identities in {'.'.join(location)}"
            )
        candidate_raw_names = [
            _dependency_parts(value, f"candidate pyproject.toml {'.'.join(location)}")[0] for value in candidate_values
        ]
        trusted_raw_names = [
            _dependency_parts(value, f"trusted pyproject.toml {'.'.join(location)}")[0] for value in trusted_values
        ]
        if candidate_raw_names != trusted_raw_names:
            raise PublishError(
                f"candidate pyproject.toml may not rewrite dependency identity spelling in {'.'.join(location)}"
            )
        _replace_nested(normalized_candidate, location, trusted_values)
    if normalized_candidate != trusted_document:
        raise PublishError("candidate pyproject.toml changed fields outside dependency version declarations")


def _validate_distribution_record(record: Mapping[str, Any], description: str) -> None:
    raw_url = record.get("url")
    if not isinstance(raw_url, str):
        raise PublishError(f"{description} has a malformed distribution URL")
    parsed = urllib.parse.urlsplit(raw_url)
    if (
        parsed.scheme != "https"
        or parsed.hostname not in TRUSTED_DISTRIBUTION_HOSTS
        or parsed.username is not None
        or parsed.password is not None
        or parsed.query
        or parsed.fragment
    ):
        raise PublishError(f"{description} contains an untrusted distribution URL")
    digest = record.get("hash")
    size = record.get("size")
    if (
        not isinstance(digest, str)
        or not digest.startswith("sha256:")
        or not SHA256_PATTERN.fullmatch(digest.removeprefix("sha256:"))
        or isinstance(size, bool)
        or not isinstance(size, int)
        or size <= 0
    ):
        raise PublishError(f"{description} distribution URL is not bound to a SHA-256 digest and size")


def _validate_lock_urls(value: object, description: str = "uv.lock") -> None:
    if isinstance(value, Mapping):
        if "url" in value:
            _validate_distribution_record(value, description)
        for key, nested in value.items():
            _validate_lock_urls(nested, f"{description}.{key}")
    elif isinstance(value, list):
        for index, nested in enumerate(value):
            _validate_lock_urls(nested, f"{description}[{index}]")


def _dependency_entry_requests(raw_entries: object, description: str) -> dict[str, set[str]]:
    if raw_entries is None:
        return {}
    if not isinstance(raw_entries, list):
        raise PublishError(f"{description} must be a dependency list")
    requests: dict[str, set[str]] = {}
    for raw_entry in raw_entries:
        entry = _mapping(raw_entry, f"{description} entry")
        name = _string(entry.get("name"), f"{description} dependency name")
        normalized_name = re.sub(r"[-_.]+", "-", name).lower()
        raw_extras = entry.get("extra", [])
        if not isinstance(raw_extras, list) or not all(
            isinstance(extra, str) and extra and extra == extra.strip() for extra in raw_extras
        ):
            raise PublishError(f"{description} dependency extras are malformed")
        requests.setdefault(normalized_name, set()).update(raw_extras)
    return requests


def _merge_dependency_requests(target: dict[str, set[str]], source: Mapping[str, set[str]]) -> None:
    for name, extras in source.items():
        target.setdefault(name, set()).update(extras)


def _validate_lock_reachability(raw_packages: list[object]) -> None:
    packages: dict[str, list[Mapping[str, Any]]] = {}
    roots: list[str] = []
    for index, raw_package in enumerate(raw_packages):
        package = _mapping(raw_package, f"uv.lock package {index}")
        name = _string(package.get("name"), f"uv.lock package {index} name")
        normalized_name = re.sub(r"[-_.]+", "-", name).lower()
        packages.setdefault(normalized_name, []).append(package)
        if package.get("source") == {"editable": "."}:
            roots.append(normalized_name)
    if roots != ["odyssey"]:
        raise PublishError("uv.lock must contain exactly one trusted Odyssey root")

    requested_extras: dict[str, set[str]] = {"odyssey": set()}
    processed_extras: dict[str, set[str]] = {}
    pending = ["odyssey"]
    while pending:
        name = pending.pop()
        extras = requested_extras[name]
        if processed_extras.get(name) == extras:
            continue
        processed_extras[name] = set(extras)
        requests: dict[str, set[str]] = {}
        found_extras: set[str] = set()
        for package in packages.get(name, []):
            _merge_dependency_requests(
                requests,
                _dependency_entry_requests(
                    package.get("dependencies"),
                    f"uv.lock package {name} dependencies",
                ),
            )
            raw_dev_dependencies = package.get("dev-dependencies")
            if raw_dev_dependencies is not None:
                dev_dependencies = _mapping(
                    raw_dev_dependencies,
                    f"uv.lock package {name} dev-dependencies",
                )
                for group, raw_entries in dev_dependencies.items():
                    _merge_dependency_requests(
                        requests,
                        _dependency_entry_requests(
                            raw_entries,
                            f"uv.lock package {name} dev-dependencies.{group}",
                        ),
                    )
            raw_optional_dependencies = package.get("optional-dependencies")
            if raw_optional_dependencies is not None:
                optional_dependencies = _mapping(
                    raw_optional_dependencies,
                    f"uv.lock package {name} optional-dependencies",
                )
                for extra in extras:
                    if extra not in optional_dependencies:
                        continue
                    found_extras.add(extra)
                    _merge_dependency_requests(
                        requests,
                        _dependency_entry_requests(
                            optional_dependencies[extra],
                            f"uv.lock package {name} optional-dependencies.{extra}",
                        ),
                    )
        missing_extras = extras - found_extras
        if missing_extras:
            raise PublishError(f"uv.lock package {name} references missing extras: {', '.join(sorted(missing_extras))}")
        for dependency, dependency_extras in requests.items():
            if dependency not in packages:
                raise PublishError(f"uv.lock references missing dependency package {dependency}")
            previous_extras = requested_extras.setdefault(dependency, set())
            changed = not dependency_extras.issubset(previous_extras)
            previous_extras.update(dependency_extras)
            if dependency not in processed_extras or changed:
                pending.append(dependency)
    unreachable = sorted(set(packages) - set(requested_extras))
    if unreachable:
        raise PublishError(f"uv.lock contains unreachable packages: {', '.join(unreachable[:10])}")


def _validate_lock_structure(content: bytes) -> None:
    document = _parse_toml_document(content, "uv.lock")
    raw_packages = document.get("package")
    if document.get("version") != 1 or not isinstance(raw_packages, list) or not raw_packages:
        raise PublishError("uv.lock has an unsupported or incomplete schema")
    editable_projects = 0
    for index, raw_package in enumerate(raw_packages):
        package = _mapping(raw_package, f"uv.lock package {index}")
        name = _string(package.get("name"), f"uv.lock package {index} name")
        source = _mapping(package.get("source"), f"uv.lock package {name} source")
        if source == {"editable": "."}:
            if re.sub(r"[-_.]+", "-", name).lower() != "odyssey":
                raise PublishError("uv.lock contains an unexpected editable dependency")
            editable_projects += 1
        elif set(source) != {"registry"} or source.get("registry") not in TRUSTED_REGISTRIES:
            raise PublishError(f"uv.lock package {name} uses an untrusted URL or non-registry source")
    if editable_projects != 1:
        raise PublishError("uv.lock must contain exactly one trusted Odyssey editable project")
    _validate_lock_reachability(raw_packages)
    _validate_lock_urls(document)


def _validate_requirement_export(content: bytes, relative_path: str) -> None:
    try:
        text = content.decode("utf-8")
    except UnicodeDecodeError as error:
        raise PublishError(f"{relative_path} is not valid UTF-8") from error
    if not text or not text.endswith("\n") or "\r" in text or "\x00" in text:
        raise PublishError(f"{relative_path} is empty or has noncanonical line endings")
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if (
            stripped.startswith(("-", "."))
            or "://" in stripped
            or " @ " in stripped
            or stripped.startswith(("file:", "git+"))
        ):
            raise PublishError(f"{relative_path} contains an include, option, path, or URL")


def _run_validation_command(
    command: list[str],
    *,
    cwd: Path,
    environment: Mapping[str, str],
    runner: Callable[..., subprocess.CompletedProcess[str]],
    description: str,
) -> subprocess.CompletedProcess[str]:
    try:
        completed = runner(
            command,
            cwd=cwd,
            check=False,
            capture_output=True,
            text=True,
            env=dict(environment),
            timeout=60,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        raise PublishError(f"{description} could not run: {error}") from error
    if completed.returncode != 0:
        detail = (completed.stderr or completed.stdout or "").strip()
        raise PublishError(f"{description} failed{f': {detail}' if detail else ''}")
    return completed


def validate_canonical_dependencies(
    bundle: ArtifactBundle,
    *,
    candidate_pyproject: bytes,
    trusted_pyproject: bytes,
    trusted_lock: bytes,
    trusted_python_version: bytes,
    runner: Callable[..., subprocess.CompletedProcess[str]] = subprocess.run,
    uv_binary: str = "uv",
) -> None:
    """Independently prove candidate files by regenerating from trusted inputs."""
    _validate_candidate_pyproject(candidate_pyproject, trusted_pyproject)
    _validate_lock_structure(bundle.files["uv.lock"])
    _validate_lock_structure(trusted_lock)
    for relative_path in ("requirements.txt", "requirements-dev.txt"):
        _validate_requirement_export(bundle.files[relative_path], relative_path)
    try:
        python_version = trusted_python_version.decode("ascii")
    except UnicodeDecodeError as error:
        raise PublishError("trusted .python-version is not ASCII") from error
    if not re.fullmatch(r"3\.\d+\n", python_version):
        raise PublishError("trusted .python-version is malformed")

    sync_script = Path(__file__).resolve().parents[1] / "sync_requirements.py"
    _read_regular_file(
        sync_script,
        maximum_bytes=MAX_REPOSITORY_DATA_BYTES,
        description="trusted requirements synchronizer",
    )
    with tempfile.TemporaryDirectory(prefix="odyssey-dependency-validation-") as temporary_directory:
        validation_root = Path(temporary_directory)
        (validation_root / PROJECT_METADATA_PATH).write_bytes(candidate_pyproject)
        (validation_root / PYTHON_VERSION_PATH).write_bytes(trusted_python_version)
        (validation_root / "uv.lock").write_bytes(trusted_lock)
        for relative_path in ("requirements.txt", "requirements-dev.txt"):
            (validation_root / relative_path).write_bytes(bundle.files[relative_path])
        environment = {
            "HOME": temporary_directory,
            "LANG": "C.UTF-8",
            "PATH": os.environ.get("PATH", ""),
            "PYTHONUTF8": "1",
            "UV_CACHE_DIR": str(validation_root / ".uv-cache"),
            "UV_PYTHON": python_version.strip(),
        }
        version = _run_validation_command(
            [uv_binary, "--version"],
            cwd=validation_root,
            environment=environment,
            runner=runner,
            description="trusted uv version check",
        )
        version_fields = version.stdout.strip().split()
        if len(version_fields) < 2 or version_fields[:2] != ["uv", TRUSTED_UV_VERSION]:
            raise PublishError(f"trusted publisher requires uv {TRUSTED_UV_VERSION}")
        regeneration_command = [uv_binary, "lock", "--no-build", "--prerelease", "allow"]
        _run_validation_command(
            regeneration_command,
            cwd=validation_root,
            environment=environment,
            runner=runner,
            description="trusted uv lock regeneration",
        )
        if (validation_root / "uv.lock").read_bytes() != bundle.files["uv.lock"]:
            raise PublishError("uv.lock is not the canonical pinned-uv result from the trusted default lock")
        offline_environment = {**environment, "UV_OFFLINE": "1"}
        _run_validation_command(
            [uv_binary, "lock", "--check", "--offline", "--prerelease", "allow"],
            cwd=validation_root,
            environment=offline_environment,
            runner=runner,
            description="trusted uv lock check",
        )
        _run_validation_command(
            [
                sys.executable,
                str(sync_script),
                "--check",
                "--repo-root",
                str(validation_root),
            ],
            cwd=validation_root,
            environment=offline_environment,
            runner=runner,
            description="trusted canonical requirements export check",
        )


