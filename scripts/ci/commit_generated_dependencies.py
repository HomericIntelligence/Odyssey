def post_graphql(
    payload: GraphQLPayload,
    token: str,
    *,
    opener: UrlOpener = urllib.request.urlopen,
) -> GraphQLPayload:
    """POST one standard-library request to GitHub's fixed GraphQL endpoint."""
    if not token:
        raise PublishError("GITHUB_TOKEN is missing")
    request = urllib.request.Request(
        GRAPHQL_URL,
        data=json.dumps(payload, separators=(",", ":")).encode(),
        headers={
            "Accept": "application/vnd.github+json",
            "Authorization": f"Bearer {token}",
            "Content-Type": "application/json",
            "User-Agent": "Odyssey-dependency-publisher",
        },
        method="POST",
    )
    response = _open_json(request, opener=opener, description="GitHub GraphQL request")
    if response is None:
        raise PublishError("GitHub GraphQL request unexpectedly returned no response")
    return response


def _open_json(
    request: urllib.request.Request,
    *,
    opener: UrlOpener,
    description: str,
    missing_ok: bool = False,
) -> GraphQLPayload | None:
    try:
        with opener(request, timeout=30) as response:
            status_code = int(response.status)
            body = response.read()
    except urllib.error.HTTPError as error:
        if missing_ok and error.code == 404:
            return None
        raise PublishError(f"{description} failed with HTTP {error.code}") from error
    except (urllib.error.URLError, TimeoutError, OSError) as error:
        raise PublishError(f"{description} failed: {error}") from error
    if missing_ok and status_code == 404:
        return None
    if status_code != 200:
        raise PublishError(f"{description} failed with HTTP {status_code}")
    try:
        decoded = json.loads(body)
    except (UnicodeDecodeError, json.JSONDecodeError) as error:
        raise PublishError(f"{description} returned malformed JSON") from error
    if not isinstance(decoded, dict):
        raise PublishError(f"{description} returned a non-object JSON value")
    return decoded


def _rest_get(
    url: str,
    *,
    token: str,
    opener: UrlOpener,
    description: str,
    missing_ok: bool = False,
) -> GraphQLPayload | None:
    request = urllib.request.Request(
        url,
        headers={
            "Accept": "application/vnd.github+json",
            "Authorization": f"Bearer {token}",
            "User-Agent": "Odyssey-dependency-publisher",
            "X-GitHub-Api-Version": "2022-11-28",
        },
        method="GET",
    )
    return _open_json(request, opener=opener, description=description, missing_ok=missing_ok)


def _api_root(repository: str) -> str:
    return f"https://api.github.com/repos/{urllib.parse.quote(repository, safe='/')}"


def verify_live_source_run(
    context: RunContext,
    *,
    token: str,
    opener: UrlOpener = urllib.request.urlopen,
) -> None:
    """Refetch and authenticate the exact workflow file and source run."""
    response = _rest_get(
        f"{_api_root(context.repository)}/actions/runs/{context.run_id}",
        token=token,
        opener=opener,
        description="source workflow run lookup",
    )
    if response is None:
        raise PublishError("source workflow run lookup unexpectedly returned no response")
    expected_fields = {
        "id": context.run_id,
        "run_attempt": context.run_attempt,
        "workflow_id": context.workflow_id,
        "name": GENERATOR_WORKFLOW,
        "path": GENERATOR_WORKFLOW_PATH,
        "event": "pull_request",
        "conclusion": "success",
        "head_branch": context.head_ref,
        "head_sha": context.head_sha,
    }
    for field, expected in expected_fields.items():
        if response.get(field) != expected:
            raise PublishError(f"source workflow run {field} does not match the trusted event")
    actor = _mapping(response.get("actor"), "source workflow run actor")
    if actor.get("login") != BOT_LOGIN:
        raise PublishError("source workflow run actor is not Dependabot")
    repository = _mapping(response.get("repository"), "source workflow run repository")
    head_repository = _mapping(response.get("head_repository"), "source workflow run head repository")
    if (
        repository.get("id") != context.repository_id
        or repository.get("full_name") != context.repository
        or head_repository.get("id") != context.head_repository_id
        or head_repository.get("full_name") != context.repository
    ):
        raise PublishError("source workflow run repository identity does not match the trusted event")

    workflow = _rest_get(
        f"{_api_root(context.repository)}/actions/workflows/{context.workflow_id}",
        token=token,
        opener=opener,
        description="source workflow identity lookup",
    )
    if workflow is None:
        raise PublishError("source workflow identity lookup unexpectedly returned no response")
    if (
        workflow.get("id") != context.workflow_id
        or workflow.get("name") != GENERATOR_WORKFLOW
        or workflow.get("path") != GENERATOR_WORKFLOW_PATH
        or workflow.get("state") != "active"
    ):
        raise PublishError("source workflow run does not belong to the exact active generator workflow")


def get_branch_head(
    repository: str,
    branch: str,
    *,
    token: str,
    opener: UrlOpener = urllib.request.urlopen,
) -> str | None:
    """Return the exact branch OID, or None after deletion."""
    _validate_repository(repository)
    _validate_branch(branch)
    encoded_branch = urllib.parse.quote(branch, safe="")
    response = _rest_get(
        f"{_api_root(repository)}/git/ref/heads/{encoded_branch}",
        token=token,
        opener=opener,
        description="Dependabot branch lookup",
        missing_ok=True,
    )
    if response is None:
        return None
    target = _mapping(response.get("object"), "Dependabot branch object")
    oid = _string(target.get("sha"), "Dependabot branch object ID")
    _validate_oid(oid, "Dependabot branch object ID")
    return oid


def get_pull_request_head(
    context: RunContext,
    *,
    pr_number: int,
    token: str,
    opener: UrlOpener = urllib.request.urlopen,
) -> str | None:
    """Verify the live open Dependabot PR and return its current head."""
    response = _rest_get(
        f"{_api_root(context.repository)}/pulls/{pr_number}",
        token=token,
        opener=opener,
        description="Dependabot pull request lookup",
        missing_ok=True,
    )
    if response is None or response.get("state") != "open":
        return None
    user = _mapping(response.get("user"), "pull request user")
    head = _mapping(response.get("head"), "pull request head")
    base = _mapping(response.get("base"), "pull request base")
    head_repository = _mapping(head.get("repo"), "pull request head repository")
    if user.get("login") != BOT_LOGIN:
        raise PublishError("live pull request author is not Dependabot")
    if head_repository.get("full_name") != context.repository:
        raise PublishError("live pull request head repository is not the target repository")
    if head.get("ref") != context.head_ref:
        raise PublishError("live pull request head branch contradicts workflow_run")
    if base.get("ref") != context.default_branch:
        raise PublishError("live pull request no longer targets the default branch")
    oid = _string(head.get("sha"), "live pull request head SHA")
    _validate_oid(oid, "live pull request head SHA")
    return oid


def get_file_at_oid(
    repository: str,
    relative_path: str,
    oid: str,
    *,
    token: str,
    opener: UrlOpener = urllib.request.urlopen,
) -> bytes:
    """Fetch one allowlisted repository file as data at an immutable Git OID."""
    if relative_path not in REPOSITORY_DATA_PATHS:
        raise PublishError(f"unexpected repository data path: {relative_path}")
    _validate_oid(oid)
    encoded_path = urllib.parse.quote(relative_path, safe="/")
    query = urllib.parse.urlencode({"ref": oid})
    response = _rest_get(
        f"{_api_root(repository)}/contents/{encoded_path}?{query}",
        token=token,
        opener=opener,
        description=f"repository content lookup for {relative_path}",
    )
    if response is None:
        raise PublishError(f"repository content lookup unexpectedly omitted {relative_path}")
    if response.get("type") != "file" or response.get("encoding") != "base64":
        raise PublishError(f"repository content for {relative_path} is not an inline base64 file")
    encoded_content = _string(response.get("content"), f"repository content for {relative_path}")
    try:
        content = base64.b64decode(encoded_content.replace("\n", ""), validate=True)
    except (ValueError, binascii.Error) as error:
        raise PublishError(f"repository content for {relative_path} is malformed base64") from error
    if len(content) > MAX_REPOSITORY_DATA_BYTES:
        raise PublishError(f"repository content for {relative_path} exceeds the size limit")
    if response.get("size") != len(content):
        raise PublishError(f"repository content size contradicts decoded bytes for {relative_path}")
    return content


def compare_artifact_to_source(
    bundle: ArtifactBundle,
    *,
    token: str,
    opener: UrlOpener = urllib.request.urlopen,
) -> tuple[str, ...]:
    """Return exact changed paths and reject a contradictory changed flag."""
    changed_paths = tuple(
        relative_path
        for relative_path in GENERATED_PATHS
        if bundle.files[relative_path]
        != get_file_at_oid(
            bundle.repository,
            relative_path,
            bundle.head_sha,
            token=token,
            opener=opener,
        )
    )
    if bundle.changed != bool(changed_paths):
        raise PublishError("artifact changed flag contradicts immutable source contents")
    return changed_paths


def _commit_headline(pr_number: int) -> str:
    return f"fix(uv): regenerate dependency files for Dependabot PR #{pr_number}"


def _commit_message(pr_number: int) -> str:
    return f"{_commit_headline(pr_number)}\n\n{DCO_BODY}"


def build_commit_payload(bundle: ArtifactBundle) -> GraphQLPayload:
    """Build a three-file, expected-parent-bound, DCO-signed mutation."""
    additions = [
        {
            "path": relative_path,
            "contents": base64.b64encode(bundle.files[relative_path]).decode("ascii"),
        }
        for relative_path in GENERATED_PATHS
    ]
    return {
        "query": CREATE_COMMIT_MUTATION,
        "variables": {
            "input": {
                "branch": {
                    "repositoryNameWithOwner": bundle.repository,
                    "branchName": bundle.head_ref,
                },
                "expectedHeadOid": bundle.head_sha,
                "message": {
                    "headline": _commit_headline(bundle.pr_number),
                    "body": DCO_BODY,
                },
                "fileChanges": {"additions": additions},
            }
        },
    }


def _validate_signature(signature_value: object) -> None:
    signature = _mapping(signature_value, "commit signature")
    if signature.get("isValid") is not True:
        raise PublishError("generated dependency commit signature is not valid")
    if signature.get("state") != "VALID":
        raise PublishError("generated dependency commit signature state is not VALID")
    if signature.get("wasSignedByGitHub") is not True:
        raise PublishError("generated dependency commit was not signed by GitHub")


def validate_create_response(response: Mapping[str, Any], *, branch: str) -> CommitResult:
    """Validate the mutation result before performing independent exact-child checks."""
    errors = response.get("errors")
    if errors:
        messages: list[str] = []
        if isinstance(errors, list):
            for error in errors:
                if isinstance(error, Mapping) and isinstance(error.get("message"), str):
                    messages.append(error["message"])
        raise PublishError(f"GitHub rejected generated dependency commit: {'; '.join(messages) or 'unknown error'}")
    data = _mapping(response.get("data"), "GraphQL data")
    mutation = _mapping(data.get("createCommitOnBranch"), "createCommitOnBranch result")
    commit = _mapping(mutation.get("commit"), "created commit")
    _validate_signature(commit.get("signature"))
    oid = _string(commit.get("oid"), "created commit OID")
    _validate_oid(oid, "created commit OID")
    url = _string(commit.get("url"), "created commit URL")
    expected_suffix = f"/commit/{oid}"
    if not url.startswith("https://github.com/") or not url.endswith(expected_suffix):
        raise PublishError("created commit URL is not a GitHub commit URL for the returned OID")
    ref = _mapping(mutation.get("ref"), "updated ref")
    if ref.get("name") not in {branch, f"refs/heads/{branch}"}:
        raise PublishError("createCommitOnBranch updated an unexpected ref")
    target = _mapping(ref.get("target"), "updated ref target")
    if target.get("oid") != oid:
        raise PublishError("createCommitOnBranch ref target contradicts the commit OID")
    return CommitResult(oid=oid, url=url)


def create_signed_commit(
    bundle: ArtifactBundle,
    *,
    token: str,
    sender: GraphQLSender = post_graphql,
) -> CommitResult:
    """Create a GitHub-signed commit only if the source OID is still current."""
    return validate_create_response(sender(build_commit_payload(bundle), token), branch=bundle.head_ref)


def verify_exact_child(
    *,
    bundle: ArtifactBundle,
    commit_oid: str,
    changed_paths: tuple[str, ...],
    token: str,
    opener: UrlOpener = urllib.request.urlopen,
    sender: GraphQLSender = post_graphql,
) -> CommitResult:
    """Verify parent, diff, message, signature, and exact file contents."""
    _validate_oid(commit_oid, "candidate child OID")
    commit_response = _rest_get(
        f"{_api_root(bundle.repository)}/commits/{commit_oid}",
        token=token,
        opener=opener,
        description="candidate generated commit lookup",
    )
    if commit_response is None:
        raise PublishError("candidate generated commit lookup unexpectedly returned no response")
    if commit_response.get("sha") != commit_oid:
        raise ExactChildMismatch("candidate generated commit lookup returned the wrong OID")
    commit_data = _mapping(commit_response.get("commit"), "candidate commit data")
    if commit_data.get("message") != _commit_message(bundle.pr_number):
        raise ExactChildMismatch("candidate generated commit message or DCO body is not exact")
    parents = commit_response.get("parents")
    if (
        not isinstance(parents, list)
        or len(parents) != 1
        or not isinstance(parents[0], Mapping)
        or parents[0].get("sha") != bundle.head_sha
    ):
        raise ExactChildMismatch("candidate generated commit is not an exact child of the workflow head")
    raw_files = commit_response.get("files")
    if not isinstance(raw_files, list):
        raise ExactChildMismatch("candidate generated commit omitted its changed file list")
    commit_paths: list[str] = []
    for entry in raw_files:
        if not isinstance(entry, Mapping) or not isinstance(entry.get("filename"), str):
            raise ExactChildMismatch("candidate generated commit has a malformed changed file entry")
        commit_paths.append(entry["filename"])
    if sorted(commit_paths) != sorted(changed_paths):
        raise ExactChildMismatch("candidate generated commit changes files outside the exact artifact diff")

    owner, name = bundle.repository.split("/", 1)
    signature_response = sender(
        {
            "query": VERIFY_COMMIT_QUERY,
            "variables": {"owner": owner, "name": name, "oid": commit_oid},
        },
        token,
    )
    if signature_response.get("errors"):
        raise ExactChildMismatch("GitHub rejected exact-child signature verification")
    data = _mapping(signature_response.get("data"), "signature query data")
    repository = _mapping(data.get("repository"), "signature query repository")
    commit = _mapping(repository.get("object"), "signature query commit")
    if commit.get("oid") != commit_oid:
        raise ExactChildMismatch("signature query returned the wrong commit")
    try:
        _validate_signature(commit.get("signature"))
    except PublishError as error:
        raise ExactChildMismatch(str(error)) from error
    url = _string(commit.get("url"), "verified commit URL")

    for relative_path in GENERATED_PATHS:
        published = get_file_at_oid(
            bundle.repository,
            relative_path,
            commit_oid,
            token=token,
            opener=opener,
        )
        if published != bundle.files[relative_path]:
            raise ExactChildMismatch(f"candidate child content does not match artifact: {relative_path}")
    return CommitResult(oid=commit_oid, url=url)


def _workflow_runs(
    repository: str,
    workflow: str,
    branch: str,
    *,
    token: str,
    opener: UrlOpener,
) -> list[Mapping[str, Any]]:
    query = urllib.parse.urlencode(
        {
            "branch": branch,
            "event": "workflow_dispatch",
            "per_page": 100,
        }
    )
    encoded_workflow = urllib.parse.quote(workflow, safe="")
    response = _rest_get(
        f"{_api_root(repository)}/actions/workflows/{encoded_workflow}/runs?{query}",
        token=token,
        opener=opener,
        description=f"workflow run lookup for {workflow}",
    )
    if response is None:
        raise PublishError(f"workflow run lookup for {workflow} unexpectedly returned no response")
    raw_runs = response.get("workflow_runs")
    if not isinstance(raw_runs, list):
        raise PublishError(f"workflow run lookup for {workflow} returned malformed data")
    return [run for run in raw_runs if isinstance(run, Mapping)]


def _dispatch_workflow(
    repository: str,
    workflow: str,
    branch: str,
    *,
    token: str,
    opener: UrlOpener,
) -> None:
    encoded_workflow = urllib.parse.quote(workflow, safe="")
    request = urllib.request.Request(
        f"{_api_root(repository)}/actions/workflows/{encoded_workflow}/dispatches",
        data=json.dumps({"ref": branch}, separators=(",", ":")).encode(),
        headers={
            "Accept": "application/vnd.github+json",
            "Authorization": f"Bearer {token}",
            "Content-Type": "application/json",
            "User-Agent": "Odyssey-dependency-publisher",
            "X-GitHub-Api-Version": "2022-11-28",
        },
        method="POST",
    )
    try:
        with opener(request, timeout=30) as response:
            status_code = int(response.status)
            response.read()
    except urllib.error.HTTPError as error:
        raise PublishError(f"workflow dispatch for {workflow} failed with HTTP {error.code}") from error
    except (urllib.error.URLError, TimeoutError, OSError) as error:
        raise PublishError(f"workflow dispatch for {workflow} failed: {error}") from error
    if status_code != 204:
        raise PublishError(f"workflow dispatch for {workflow} failed with HTTP {status_code}")


def authenticate_required_workflows(
    *,
    repository: str,
    commit_oid: str,
    trusted_default_oid: str,
    token: str,
    opener: UrlOpener = urllib.request.urlopen,
) -> None:
    """Require every dispatched workflow blob to equal the immutable trusted copy."""
    _validate_repository(repository)
    _validate_oid(commit_oid, "published GraphQL commit OID")
    _validate_oid(trusted_default_oid, "trusted default-branch OID")
    for workflow_path in REQUIRED_WORKFLOW_PATHS:
        trusted_content = get_file_at_oid(
            repository,
            workflow_path,
            trusted_default_oid,
            token=token,
            opener=opener,
        )
        candidate_content = get_file_at_oid(
            repository,
            workflow_path,
            commit_oid,
            token=token,
            opener=opener,
        )
        if candidate_content != trusted_content:
            raise PublishError(
                f"refusing to dispatch modified required workflow {workflow_path}; "
                "Dependabot branch must be updated from the trusted default branch"
            )


def dispatch_required_workflows(
    *,
    repository: str,
    branch: str,
    commit_oid: str,
    trusted_default_oid: str,
    token: str,
    opener: UrlOpener = urllib.request.urlopen,
    sleeper: Callable[[float], None] = time.sleep,
    poll_attempts: int = 10,
) -> int:
    """Idempotently dispatch the literal allowlist and bind every run to the OID."""
    _validate_repository(repository)
    _validate_branch(branch)
    _validate_oid(commit_oid, "published GraphQL commit OID")
    _validate_oid(trusted_default_oid, "trusted default-branch OID")
    if poll_attempts <= 0:
        raise PublishError("workflow dispatch poll attempts must be positive")
    authenticate_required_workflows(
        repository=repository,
        commit_oid=commit_oid,
        trusted_default_oid=trusted_default_oid,
        token=token,
        opener=opener,
    )
    dispatched = 0
    for workflow in REQUIRED_WORKFLOWS:
        if get_branch_head(repository, branch, token=token, opener=opener) != commit_oid:
            raise StaleBranch(f"branch moved before dispatching {workflow}")
        runs = _workflow_runs(repository, workflow, branch, token=token, opener=opener)
        if any(run.get("head_sha") == commit_oid for run in runs):
            print(f"Already dispatched {workflow} on {commit_oid}; resuming")
            continue

        _dispatch_workflow(repository, workflow, branch, token=token, opener=opener)
        dispatched += 1
        for attempt in range(poll_attempts):
            runs = _workflow_runs(repository, workflow, branch, token=token, opener=opener)
            matching_runs = [run for run in runs if run.get("head_sha") == commit_oid]
            if matching_runs:
                run_url = next(
                    (str(run["html_url"]) for run in matching_runs if isinstance(run.get("html_url"), str)),
                    "run created",
                )
                print(f"Dispatched {workflow} on {commit_oid}: {run_url}")
                break
            if attempt + 1 < poll_attempts:
                sleeper(1.0)
        else:
            raise PublishError(f"workflow dispatch for {workflow} did not bind to GraphQL OID {commit_oid}")
    if get_branch_head(repository, branch, token=token, opener=opener) != commit_oid:
        raise StaleBranch("branch moved during required workflow dispatch")
    return dispatched


def wait_for_published_head(
    *,
    context: RunContext,
    pr_number: int,
    expected_oid: str,
    token: str,
    opener: UrlOpener = urllib.request.urlopen,
    sleeper: Callable[[float], None] = time.sleep,
    poll_attempts: int = 10,
) -> bool:
    """Wait for branch and PR APIs to expose the verified child.

    A genuinely newer OID is stale and returns False. Temporary visibility of
    the original parent is retried so a successful mutation cannot silently
    finish without dispatching its required checks.
    """
    if poll_attempts <= 0:
        raise PublishError("published-head poll attempts must be positive")
    for attempt in range(poll_attempts):
        current_pr_head = get_pull_request_head(
            context,
            pr_number=pr_number,
            token=token,
            opener=opener,
        )
        current_branch_head = get_branch_head(
            context.repository,
            context.head_ref,
            token=token,
            opener=opener,
        )
        if current_pr_head == expected_oid and current_branch_head == expected_oid:
            return True
        observed = {current_pr_head, current_branch_head}
        if None in observed or not observed.issubset({context.head_sha, expected_oid}):
            return False
        if attempt + 1 < poll_attempts:
            sleeper(1.0)
    raise PublishError(f"live pull request did not converge on published commit {expected_oid}")


def publish_dependencies(
    *,
    context: RunContext,
    bundle: ArtifactBundle,
    trusted_default_oid: str,
    token: str,
    opener: UrlOpener = urllib.request.urlopen,
    sender: GraphQLSender = post_graphql,
    sleeper: Callable[[float], None] = time.sleep,
) -> PublishResult:
    """Publish once, resume safely after partial completion, or no-op if stale."""
    _validate_oid(trusted_default_oid, "trusted default-branch OID")
    live_pr_head = get_pull_request_head(
        context,
        pr_number=bundle.pr_number,
        token=token,
        opener=opener,
    )
    live_branch_head = get_branch_head(context.repository, context.head_ref, token=token, opener=opener)
    if live_pr_head is None or live_branch_head is None:
        return PublishResult("stale", None, 0)

    validate_published_dependency_candidate(
        bundle,
        trusted_default_oid=trusted_default_oid,
        token=token,
        opener=opener,
    )
    changed_paths = compare_artifact_to_source(bundle, token=token, opener=opener)
    if not changed_paths:
        if live_pr_head != bundle.head_sha or live_branch_head != bundle.head_sha:
            return PublishResult("stale", None, 0)
        return PublishResult("unchanged", bundle.head_sha, 0)

    verified: CommitResult | None = None
    if live_pr_head != live_branch_head:
        observed_heads = {live_pr_head, live_branch_head}
        child_candidates = observed_heads - {bundle.head_sha}
        if bundle.head_sha not in observed_heads or len(child_candidates) != 1:
            return PublishResult("stale", None, 0)
        candidate_oid = next(iter(child_candidates))
        try:
            verified = verify_exact_child(
                bundle=bundle,
                commit_oid=candidate_oid,
                changed_paths=changed_paths,
                token=token,
                opener=opener,
                sender=sender,
            )
        except ExactChildMismatch:
            return PublishResult("stale", None, 0)

        if not wait_for_published_head(
            context=context,
            pr_number=bundle.pr_number,
            expected_oid=verified.oid,
            token=token,
            opener=opener,
            sleeper=sleeper,
        ):
            return PublishResult("stale", None, 0)
        live_branch_head = verified.oid

    if live_branch_head == bundle.head_sha:
        try:
            created = create_signed_commit(bundle, token=token, sender=sender)
        except PublishError:
            raced_head = get_branch_head(
                context.repository,
                context.head_ref,
                token=token,
                opener=opener,
            )
            if raced_head is None or raced_head == bundle.head_sha:
                raise
            live_branch_head = raced_head
        else:
            live_branch_head = created.oid

    if live_branch_head == bundle.head_sha:
        raise PublishError("GitHub did not advance the Dependabot branch")
    if verified is None:
        try:
            verified = verify_exact_child(
                bundle=bundle,
                commit_oid=live_branch_head,
                changed_paths=changed_paths,
                token=token,
                opener=opener,
                sender=sender,
            )
        except ExactChildMismatch:
            return PublishResult("stale", None, 0)

        if not wait_for_published_head(
            context=context,
            pr_number=bundle.pr_number,
            expected_oid=verified.oid,
            token=token,
            opener=opener,
            sleeper=sleeper,
        ):
            return PublishResult("stale", None, 0)
    dispatched = dispatch_required_workflows(
        repository=context.repository,
        branch=context.head_ref,
        commit_oid=verified.oid,
        trusted_default_oid=trusted_default_oid,
        token=token,
        opener=opener,
        sleeper=sleeper,
    )
    return PublishResult("published", verified.oid, dispatched)


def _required_environment(name: str) -> str:
    value = os.environ.get(name, "")
    if not value:
        raise PublishError(f"required environment variable is missing: {name}")
    return value


def _positive_environment_integer(name: str) -> int:
    try:
        value = int(_required_environment(name))
    except ValueError as error:
        raise PublishError(f"{name} must be an integer") from error
    return _integer(value, name)


def _package_from_cli(args: argparse.Namespace) -> None:
    changed_value = _required_environment("DEPS_CHANGED")
    if changed_value not in {"true", "false"}:
        raise PublishError("DEPS_CHANGED must be 'true' or 'false'")
    package_artifact(
        repo_root=args.repo_root.resolve(),
        artifact_root=args.artifact_root.resolve(),
        repository=_required_environment("TARGET_REPOSITORY"),
        pr_number=_positive_environment_integer("PR_NUMBER"),
        head_repository=_required_environment("HEAD_REPOSITORY"),
        head_ref=_required_environment("HEAD_REF"),
        head_sha=_required_environment("HEAD_SHA"),
        run_id=_positive_environment_integer("WORKFLOW_RUN_ID"),
        run_attempt=_positive_environment_integer("WORKFLOW_RUN_ATTEMPT"),
        producer_status=_required_environment("PRODUCER_STATUS"),
        changed=changed_value == "true",
        snapshot_path=args.snapshot_path.resolve(),
    )


def _snapshot_from_cli(args: argparse.Namespace) -> None:
    write_dependency_snapshot(
        repo_root=args.repo_root.resolve(),
        snapshot_path=args.snapshot_path.resolve(),
    )


def _publish_from_cli(args: argparse.Namespace) -> PublishResult:
    repository = _required_environment("TARGET_REPOSITORY")
    token = _required_environment("GITHUB_TOKEN")
    trusted_default_oid = _required_environment("TRUSTED_DEFAULT_SHA")
    _validate_oid(trusted_default_oid, "TRUSTED_DEFAULT_SHA")
    context = load_run_context(args.event_path.resolve(), target_repository=repository)
    verify_live_source_run(context, token=token)
    bundle = download_validated_artifact(context, token=token)
    return publish_dependencies(
        context=context,
        bundle=bundle,
        trusted_default_oid=trusted_default_oid,
        token=token,
    )


def main(argv: Sequence[str] | None = None) -> int:
    """Run the producer packager or trusted default-branch publisher."""
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)
    package_parser = subparsers.add_parser("package")
    package_parser.add_argument("--repo-root", type=Path, required=True)
    package_parser.add_argument("--artifact-root", type=Path, required=True)
    package_parser.add_argument("--snapshot-path", type=Path, required=True)
    snapshot_parser = subparsers.add_parser("snapshot")
    snapshot_parser.add_argument("--repo-root", type=Path, required=True)
    snapshot_parser.add_argument("--snapshot-path", type=Path, required=True)
    publish_parser = subparsers.add_parser("publish")
    publish_parser.add_argument("--event-path", type=Path, required=True)
    args = parser.parse_args(argv)

    try:
        if args.command == "package":
            _package_from_cli(args)
            print(f"Packaged exact {ARTIFACT_NAME} artifact")
        elif args.command == "snapshot":
            _snapshot_from_cli(args)
            print("Snapshotted exact verified dependency files")
        else:
            result = _publish_from_cli(args)
            if result.status == "stale":
                print("Dependabot branch is stale, moved, closed, or non-exact; no write performed")
            elif result.status == "unchanged":
                print("Generated dependency files are unchanged; no write or dispatch needed")
            else:
                print(
                    f"Published verified GitHub-signed commit {result.oid}; "
                    f"dispatched {result.dispatched} missing required workflows"
                )
    except StaleBranch as error:
        print(f"Dependabot branch became stale; stopped safely: {error}")
        return 0
    except (PublishError, OSError, ValueError) as error:
        print(f"ERROR: dependency artifact publication failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
