class PublishError(RuntimeError):
    """Raised when the trusted publication contract is not satisfied."""


class StaleBranch(RuntimeError):
    """Signals a safe no-op because the Dependabot branch moved or disappeared."""


class ExactChildMismatch(PublishError):
    """Raised when a moved branch is not the exact trusted generated child."""


class _NoRedirectHandler(urllib.request.HTTPRedirectHandler):
    """Expose GitHub's signed artifact redirect without forwarding the token."""

    def redirect_request(
        self,
        request: urllib.request.Request,
        file_pointer: Any,
        code: int,
        message: str,
        headers: HTTPMessage,
        new_url: str,
    ) -> None:
        del request, file_pointer, code, message, headers, new_url
        return None


